//! Commutation mode and the phase-current law (FOC, `id = 0`).
//!
//! ## Pinned d-axis convention (product-owner approved)
//!
//! The **d-axis** is defined along the mover field: the alternating magnet
//! array has `B_z` peaking at the magnet centre, so the d-axis frame is the
//! one where `x ≡ 0 (mod τ_p)` is a magnet centre and the mover field phasor
//! points along d. The **q-axis** is 90° electrical ahead of d. The approved
//! control decision for this coreless motor (no saliency → no reluctance
//! term) is **`id = 0`: pure q-axis drive** — the standard
//! maximum-thrust-per-ampere choice. This is the glossary's *90-degree rule*:
//! FOC regulates the stator (phase-current) field orthogonal (90°
//! electrical) to the mover field.
//!
//! ## Derivation chain (90° rule → per-coil law)
//!
//! 1. **90° rule**: FOC regulates the stator field orthogonal (90°
//!    electrical) to the mover field — pure q-axis (`id = 0`) — for maximum
//!    thrust per ampere.
//! 2. **q-axis alignment**: with the d-axis pinned at the magnet centres,
//!    the mover field along the track is `B_z(x, p) ∝ cos(π(x−p)/τ_p)`, i.e.
//!    the field phasor sits on the d-axis at electrical angle
//!    `θ_e = π·x/τ_p = 2π·x/(2τ_p)`. Pure q-axis drive puts each coil's
//!    current in phase with its local `B_z` (the Lorentz force
//!    `F = I·L×B` is maximal per ampere under the orthogonal air-gap
//!    geometry when the current is in phase with the local vertical field) —
//!    this IS the 90° rule expressed in the field frame: the stator MMF
//!    generated by that current distribution stands 90° electrical from the
//!    mover d-field.
//! 3. **General per-coil offset law** (glossary): a coil displaced Δx
//!    spatially from the reference coil carries an electrical phase shift
//!    `π·Δx/τ_p`. Adjacent coils are spaced one phase-band pitch apart
//!    (`Δx = τ_band = r·τ_p/phases`, Vernier ratio `r` included), so coil
//!    `p` runs an offset `p·π·τ_band/τ_p` — 60° for the default 3-phase 1:1
//!    layout, `0.8·60°` for the 4:5 Vernier.
//!
//! Putting it together, the per-coil current law is
//!
//! ```text
//! I_p = I_pk · cos(θ_e − p·π·τ_band/τ_p),   θ_e = 2π·x/(2τ_p) + phase_shift
//! ```
//!
//! Whether the per-phase current is `sin` or `cos` of θ_e is a
//! reference-frame (d-axis alignment) convention, **not** a physics
//! difference: `cos(α) = sin(α + π/2)` is the same waveform rotated 90°
//! electrical. The glossary's classic balanced 120° law
//! `I_p = I_pk·sin(θ_e − p·2π/3)` is the special case for coils spaced
//! `2τ_p/3` (phase_offset = 2π/3) viewed from a frame rotated 90° from the
//! one pinned here; those currents sum to zero at every θ_e
//! (pinned by `test_balanced_120deg_law_special_case` below).
//!
//! A pole-matched star explicitly sets `balanced_three_phase_drive`. Its
//! physical belts remain 60 degrees apart but alternating terminal polarity
//! gives directed A/B/C axes 120 degrees apart. That command uses balanced
//! terminal offsets, not physical band centerlines. The common alignment is
//! still obtained from the signed routed force response, not a hardware encoder.

use serde::{Deserialize, Serialize};

use crate::params::SimulationInput;

/// Commutation strategy for phase current selection.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CommutationMode {
    /// Sinusoidal FOC drive at the glossary-normative 90-degree rule with the
    /// pinned `id = 0` d-axis convention (pure q-axis, maximum thrust per
    /// ampere): `I_p = I_pk·cos(θ_e − p·π·τ_band/τ_p)` where τ_band is the
    /// phase-band pitch (`r·τ_p/phases`) — adjacent coils are spaced one
    /// phase-band pitch apart, giving a 60° electrical offset for the
    /// default 3-phase 1:1 winding. The classic balanced 120° law
    /// corresponds to the same law with coils spaced `2τ_p/3`
    /// (phase_offset = 2π/3) and a 90° frame rotation. See the module docs
    /// for the derivation chain.
    MaxThrust,
    /// Only Phase A energised at full peak current; B and C zero.
    PhaseAOnly,
}

impl Default for CommutationMode {
    fn default() -> Self {
        Self::MaxThrust
    }
}

/// Return the signed phase currents [A] for the given mover position.
///
/// Implements the pinned FOC law (module docs hold the full derivation
/// chain: 90° rule → q-axis alignment → per-coil cos law via the general
/// per-coil offset law). With `id = 0` (pure q-axis):
///
/// ```text
/// I_p = I_pk · cos(θ_e − offset_p)
/// θ_e = 2π·x/(2τ_p) + phase_shift
/// ```
///
/// The per-coil offset `offset_p` comes from the **declared phase bands**
/// (kata hzs2) when `config.phase_bands` carries a band for every coil slot
/// in `phase_labels`: coil p runs `π·(x_p − x_ref)/τ_p` with `x_p` its
/// band's declared centerline (matched by phase label) and `x_ref` the first
/// coil slot's centerline — the general per-coil offset law read from the
/// routing contract's laid-out band positions. The analytic fallback
/// (uniform `p·π·τ_band/τ_p` with `τ_band = spacing_ratio·τ_p/phases`)
/// applies when no bands are declared or any coil slot is unmatched.
///
/// `phase_shift` is the dynamic polarity term set by the
/// [`ForceEvaluator`](crate::magnetic::force_eval::ForceEvaluator)'s 3-point
/// self-calibration guard. Usually 0 or π; a winding whose reference is
/// displaced can require a common electrical alignment as well.
///
/// Free function so it can be called from parallel closures without borrowing
/// `self` (which would require `&self` to be `Sync` — it is, but extracting
/// the logic avoids the borrow entirely).
pub(crate) fn commutation_currents(
    commutation: CommutationMode,
    phase_shift: f64,
    config: &SimulationInput,
    mover_position_m: f64,
    phase_labels: &[&str],
) -> Vec<f64> {
    let i_pk = config.max_current_a;

    if commutation == CommutationMode::PhaseAOnly {
        return phase_labels.iter().map(|label| {
            if Some(label) == phase_labels.first() { i_pk } else { 0.0 }
        }).collect();
    }

    // MaxThrust — FOC, id = 0 (pure q-axis; module docs hold the derivation
    // chain: 90° rule → q-axis alignment → per-coil cos law).
    //
    // θ_e = π·x/τ_p = 2π·x/(2τ_p): the d-axis frame is pinned at the magnet
    // centres (x ≡ 0 mod τ_p), where B_z of the alternating array peaks
    // (`B_z(x, p) ∝ cos(π(x−p)/τ_p)`). Pure q-axis drive puts the per-coil
    // current in phase with the local B_z, so the stator MMF stands 90°
    // electrical from the mover d-field (the glossary 90-degree rule) and
    // the Lorentz thrust per ampere is maximal.
    //
    // Per-coil offset = π·τ_band/τ_p — the general per-coil offset law for
    // coils spaced one phase-band pitch apart (matches the phase-band layout
    // the routing crate generates); π/3 (60°) for the default 3-phase 1:1
    // layout, r·π/3 for a Vernier spacing ratio r.
    let theta_e = 2.0 * std::f64::consts::PI * mover_position_m / (2.0 * config.pole_pitch_m())
        + phase_shift;
    let offsets = if config.balanced_three_phase_drive {
        // The pole-matched generator has already connected the physical
        // belts with alternating polarity and labeled the terminals A/B/C.
        // Do not mistake its 60-degree physical belt pitch for directed axes.
        phase_labels.iter().map(|label| match *label {
            "A" => 0.0, "B" => std::f64::consts::TAU / 3.0,
            "C" => 2.0 * std::f64::consts::TAU / 3.0,
            _ => f64::NAN, // Invalid labels must not produce a usable command.
        }).collect()
    } else {
        declared_phase_offsets(config, phase_labels)
            .unwrap_or_else(|| analytic_phase_offsets(config, phase_labels))
    };

    (0..phase_labels.len())
        .map(|p| i_pk * (theta_e - offsets[p]).cos())
        .collect()
}

/// Per-coil electrical offsets [rad] from the declared phase bands (kata
/// hzs2): each coil slot is matched to a declared band by its phase label
/// and runs `π·(x_p − x_ref)/τ_p` with `x_p` its band's declared centerline
/// and `x_ref` the first coil slot's centerline (the general per-coil offset
/// law — glossary "Commutation" — read from the laid-out band positions).
/// Returns `None` — the caller falls back to the analytic law — unless every
/// coil slot matches a declared band and the pole pitch is positive.
fn declared_phase_offsets(config: &SimulationInput, phase_labels: &[&str]) -> Option<Vec<f64>> {
    if phase_labels.is_empty() || config.phase_bands.is_empty() {
        return None;
    }
    let tau_p = config.pole_pitch_m();
    if !(tau_p > 0.0) {
        return None;
    }
    let centerline = |label: &str| -> Option<f64> {
        config
            .phase_bands
            .iter()
            .find(|band| band.phase == label)
            .map(|band| band.centerline_m)
    };
    let reference = centerline(phase_labels[0])?;
    let mut offsets = Vec::with_capacity(phase_labels.len());
    for label in phase_labels {
        let x = centerline(label)?;
        offsets.push(std::f64::consts::PI * (x - reference) / tau_p);
    }
    Some(offsets)
}

/// Analytic per-coil offsets [rad]: `p·π·τ_band/τ_p` for coils spaced one
/// (Vernier-adjusted) phase-band pitch apart — the fallback when no phase
/// bands are declared.
fn analytic_phase_offsets(config: &SimulationInput, phase_labels: &[&str]) -> Vec<f64> {
    let phase_offset = std::f64::consts::PI * config.phase_band_pitch_m() / config.pole_pitch_m();
    // A coil slot is a (layer, net) pair, not a new electrical phase.
    // Every layer of the same net must receive the same current.
    let mut phases = Vec::new();
    phase_labels.iter().map(|label| {
        let p = match phases.iter().position(|known| known == label) {
            Some(p) => p,
            None => { phases.push(*label); phases.len() - 1 }
        };
        p as f64 * phase_offset
    }).collect()
}

