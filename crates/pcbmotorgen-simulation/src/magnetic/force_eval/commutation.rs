    /// Glossary balanced-3-phase law as the special case of the general
    /// per-coil offset law for a 2τ_p/3-spaced winding.
    ///
    /// Coils spaced `Δx = 2τ_p/3` apart run an electrical offset
    /// `π·Δx/τ_p = 2π/3` (120°). With `spacing_ratio = 2.0` the
    /// phase-band pitch is `2τ_p/3`, so the implemented law becomes
    /// `I_p = I_pk·cos(θ_e − p·2π/3)`.
    ///
    /// The glossary's balanced law is written `I_p = I_pk·sin(θ_e − p·2π/3)`.
    /// Whether the current is sin or cos of θ_e is the pinned d-axis frame
    /// convention, not a physics difference: `cos(α) = sin(α + π/2)` — the
    /// same balanced set seen from a frame rotated 90° electrical. This test
    /// pins both the equivalence and the defining property of the balanced
    /// law: the three currents **sum to zero at every θ_e**.
    #[test]
    fn test_balanced_120deg_law_special_case() {
        // spacing_ratio = 2.0 → phase_band_pitch = 2·τ_p/3 → phase_offset = 2π/3
        let cfg = SimulationInput {
            spacing_ratio: 2.0,
            ..SimulationInput::default()
        };
        let tau_p = cfg.pole_pitch_m();
        let i_pk = cfg.max_current_a;
        let two_pi_3 = 2.0 * std::f64::consts::PI / 3.0;
        let pi_2 = std::f64::consts::FRAC_PI_2;

        // Sweep a full electrical period. θ_e = 2π·x/(2τ_p) = π·x/τ_p, so
        // x = θ_e·τ_p/π; steps of 1 mm give θ_e steps of π/12 (default
        // τ_p = 12 mm), covering [0, 2π] inclusively.
        for k in 0..=24u32 {
            let theta_e = k as f64 * std::f64::consts::PI / 12.0;
            let x = theta_e * tau_p / std::f64::consts::PI;
            let currents =
                commutation_currents(CommutationMode::MaxThrust, 0.0, &cfg, x, &["A", "B", "C"]);

            // (a) Balanced 3-phase law: currents sum to zero at every θ_e.
            let sum: f64 = currents.iter().sum();
            assert!(
                sum.abs() < 1e-9,
                "balanced 120° law must sum to zero at θ_e={theta_e:.4}, got {sum}"
            );

            // (b) Matches I_pk·sin(θ_e − p·2π/3) up to the pinned 90° frame
            // rotation: cos(θ_e − p·2π/3) = sin(θ_e − p·2π/3 + π/2).
            for (p, &i) in currents.iter().enumerate() {
                let expected = i_pk * (theta_e - p as f64 * two_pi_3 + pi_2).sin();
                assert!(
                    (i - expected).abs() < 1e-9,
                    "phase {p} at θ_e={theta_e:.4}: got {i}, expected \
                     I_pk·sin(θ_e − p·2π/3 + π/2) = {expected}"
                );
            }
        }
    }

